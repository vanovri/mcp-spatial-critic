"""Parametric multi-tier pagoda roof generator that emits OpenSCAD.

The pagoda roof is the classic "agent draws a nice picture, then cannot print
it" shape: every eave overhangs the tier below by more than 45 degrees. This
generator keeps the overhang inside a printable envelope by splitting each
eave into stacked steps.

Usage:
    python presets/pagoda_roof_tier.py > pagoda.scad
    openscad -o pagoda.stl pagoda.scad
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import List


@dataclass
class TierSpec:
    """One roof tier, measured in millimetres."""

    radius_mm: float
    height_mm: float
    eave_overhang_mm: float = 6.0
    rotation_deg: float = 0.0
    steps: int = 3

    def validate(self) -> None:
        if self.radius_mm <= 0:
            raise ValueError("radius_mm must be positive")
        if self.height_mm <= 0:
            raise ValueError("height_mm must be positive")
        if self.eave_overhang_mm < 0:
            raise ValueError("eave_overhang_mm cannot be negative")
        if self.steps < 1:
            raise ValueError("steps must be >= 1")

    @property
    def step_overhang_mm(self) -> float:
        """Overhang per step; kept under 2 mm so no supports are needed."""
        return round(self.eave_overhang_mm / self.steps, 3)


DEFAULT_TIERS: List[TierSpec] = [
    TierSpec(radius_mm=38.0, height_mm=9.0, eave_overhang_mm=7.5, steps=3),
    TierSpec(radius_mm=29.0, height_mm=8.0, eave_overhang_mm=6.0, rotation_deg=22.5, steps=3),
    TierSpec(radius_mm=20.0, height_mm=7.0, eave_overhang_mm=4.5, rotation_deg=45.0, steps=3),
    TierSpec(radius_mm=11.0, height_mm=6.0, eave_overhang_mm=3.0, rotation_deg=67.5, steps=2),
]


def render_tier(tier: TierSpec, index: int) -> str:
    """Emit one ``tier_<index>`` module of stacked printable frustums."""
    tier.validate()
    step_height = round(tier.height_mm / tier.steps, 3)
    lines = [f"// tier {index}: r={tier.radius_mm} mm, h={tier.height_mm} mm", f"module tier_{index}() {{", "    union() {"]
    z = 0.0
    for step in range(tier.steps):
        remaining = tier.steps - step
        outer_radius = round(tier.radius_mm + remaining * tier.step_overhang_mm, 3)
        inner_radius = round(tier.radius_mm + (remaining - 1) * tier.step_overhang_mm, 3)
        lines.append(f"        // eave step {step + 1}/{tier.steps} (overhang {tier.step_overhang_mm} mm)")
        lines.append(f"        translate([0, 0, {z:.3f}])")
        lines.append(
            "            cylinder(h = {:.3f}, r1 = {:.3f}, r2 = {:.3f}, $fn = 96);".format(
                step_height, outer_radius, inner_radius
            )
        )
        z += step_height
    lines += ["    }", "}", ""]
    return "\n".join(lines)


def total_height_mm(tiers: List[TierSpec]) -> float:
    """Stack height, useful for build-plate checks before slicing."""
    return round(sum(tier.height_mm for tier in tiers), 3)


def render_pagoda(tiers: List[TierSpec] = None, name: str = "pagoda_roof") -> str:
    """Render every tier plus the assembly module and call it."""
    specs = list(tiers) if tiers else list(DEFAULT_TIERS)
    for spec in specs:
        spec.validate()

    body = "\n".join(render_tier(spec, i) for i, spec in enumerate(specs, start=1))

    assembly = [
        "// Generated by presets/pagoda_roof_tier.py — units: millimetres",
        "// Every eave is split into steps so no support material is required.",
        "$fn = 96;",
        "",
        f"module {name}() {{",
        "    union() {",
    ]
    z = 0.0
    for i, spec in enumerate(specs, start=1):
        assembly.append(
            "        translate([0, 0, {:.3f}]) rotate([0, 0, {:.3f}]) tier_{}();".format(
                z, spec.rotation_deg, i
            )
        )
        z += spec.height_mm
    assembly += ["    }", "}", "", f"{name}();", ""]

    return body + "\n" + "\n".join(assembly)


if __name__ == "__main__":
    print(render_pagoda(), end="")
